"""Checkpoint-local model file for non-uniform expert counts.

mlx-vlm sizes every MoE block from one ``num_experts``; a non-uniformly pruned
checkpoint ships this file (config ``model_file``) so each layer gets its own count
from config ``expert_counts``. Everything else is the stock mlx-vlm architecture.
"""

import types

SHIM_FILENAME = "pruned_moe.py"

TEMPLATE = '''"""Generated by build.make: per-layer routed-expert counts for {base}."""

from dataclasses import dataclass, replace
from typing import List, Optional

from mlx_vlm.models import {base} as _base
from mlx_vlm.models.{base} import *  # noqa: F401,F403

LanguageModel = _base.LanguageModel
VisionModel = _base.VisionModel
_EXPERTS_ATTR = "{experts_attr}"


@dataclass
class ModelConfig(_base.ModelConfig):
    expert_counts: Optional[List[Optional[int]]] = None


class Model(_base.Model):
    def __init__(self, config):
        super().__init__(config)
        text_config = config.text_config
        default = getattr(text_config, _EXPERTS_ATTR)
        layers = self.language_model.model.layers
        for layer, count in zip(layers, config.expert_counts or []):
            mlp = getattr(layer, "mlp", None)
            if not count or count == default or mlp is None or "switch_mlp" not in mlp:
                continue
            layer.mlp = type(mlp)(replace(text_config, **{{_EXPERTS_ATTR: int(count)}}))
'''


def render(base_model_type: str, experts_attr: str) -> str:
    return TEMPLATE.format(base=base_model_type, experts_attr=experts_attr)


def load_module(source: str, name: str = "pruned_moe_shim"):
    module = types.ModuleType(name)
    exec(compile(source, name, "exec"), module.__dict__)
    return module
