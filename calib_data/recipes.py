"""Per-source converters: raw dataset rows -> chat messages (+ tools) -> token ids in the target template.

Every recipe is a generator over a pre-shuffled, split-filtered pool that yields (source_key, tokens).
"""

import difflib
import hashlib
import html
import json
import math
import re
from dataclasses import dataclass
from typing import Callable

from .render import Renderer


@dataclass
class Ctx:
    r: Renderer
    rng: object
    max_len: dict
    longctx: tuple


@dataclass(frozen=True)
class Recipe:
    name: str
    domain: str
    source: str
    weight: float
    make: Callable
    key: Callable = lambda row: row["_src"]
    shard: tuple = (0, 1)


def stable_hash(s: str) -> int:
    return int(hashlib.sha1(s.encode()).hexdigest()[:15], 16)


def loguniform(rng, lo, hi):
    return int(math.exp(rng.uniform(math.log(lo), math.log(hi))))


def think_split(text: str):
    if "</think>" not in text:
        return None, text.strip()
    head, _, tail = text.partition("</think>")
    return head.split("<think>", 1)[-1].strip(), tail.strip()


def assistant(content, reasoning=None, tool_calls=None):
    m = {"role": "assistant", "content": content}
    if reasoning:
        m["reasoning_content"] = reasoning
    if tool_calls:
        m["tool_calls"] = tool_calls
    return m


def tool_call(i, name, args):
    return {"id": f"call_{i}", "type": "function", "function": {"name": name, "arguments": args}}


